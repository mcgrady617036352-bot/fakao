function clampScore(x, max) {
  const n = Number(x);
  if (!Number.isFinite(n)) return 0;
  return Math.max(0, Math.min(max, Math.round(n * 100) / 100));
}

function normalizeReport(report, questionId, subId) {
  const s = getSubquestion(questionId, subId);
  const result = { ...report, maxScore: s.score, pointResults: [], score: 0 };
  const supplied = new Map();
  const duplicatePointIds = [];
  for (const x of (report.pointResults || [])) { if (supplied.has(x.pointId)) duplicatePointIds.push(x.pointId); else supplied.set(x.pointId, x); }
  for (const point of s.points) {
    const r = supplied.get(point.id) || {};
    result.pointResults.push({
      pointId: point.id,
      score: clampScore(r.score, point.score),
      maxScore: point.score,
      status: r.status || "未命中",
      evidence: r.evidence || "",
      reason: r.reason || ""
    });
  }
  result.score = Math.round(result.pointResults.reduce((a, x) => a + x.score, 0) * 100) / 100;
  result.validation = { duplicatePointIds, unknownPointIds: [...supplied.keys()].filter(id => !s.points.some(p => p.id === id)) };
  return result;
}

function buildQuestionSummary(questionId, subReports) {
  const q = QUESTIONS.find(x => x.id === Number(questionId));
  if (!q) throw new Error(`不存在第${questionId}题`);
  const normalized = q.subquestions.map(s => {
    const r = subReports.find(x => x.subId === s.id) || { score: 0, maxScore: s.score };
    return { subId: s.id, score: clampScore(r.score, s.score), maxScore: s.score, feedback: r.feedback || "" };
  });
  return { questionId: q.id, title: q.title, score: normalized.reduce((a, x) => a + x.score, 0), maxScore: 40, subquestions: normalized };
}

