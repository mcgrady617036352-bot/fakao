function validateRubric() {
  const errors = [];
  if (QUESTIONS.length !== 10) errors.push(`题目数量错误：${QUESTIONS.length}`);
  for (const q of QUESTIONS) {
    const sum = q.subquestions.reduce((a, s) => a + s.score, 0);
    if (sum !== 40) errors.push(`第${q.id}题小问合计${sum}分，不是40分`);
    for (const s of q.subquestions) {
      const ps = s.points.reduce((a, x) => a + x.score, 0);
      if (ps !== s.score) errors.push(`${s.id}采分点合计${ps}分，小问分值${s.score}分`);
      if (!s.examAnswer || !s.fullAnswer || !s.keywords?.length) errors.push(`${s.id}缺少答案或关键词`);
    }
  }
  return { ok: errors.length === 0, errors };
}

function getSubquestion(questionId, subId) {
  const q = QUESTIONS.find(x => x.id === Number(questionId));
  if (!q) throw new Error(`不存在第${questionId}题`);
  const s = q.subquestions.find(x => x.id === subId);
  if (!s) throw new Error(`第${questionId}题不存在小问${subId}`);
  return s;
}

